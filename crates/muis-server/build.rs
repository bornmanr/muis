//! Embeds `src-ui/dist` into the server binary at compile time.
//!
//! A missing `dist` is not an error: the binary still builds (so `cargo test
//! --workspace` works without Node) and serves a placeholder page telling you
//! to run `npm run build --prefix src-ui`. `MUIS_UI_DIST` overrides the
//! directory, which is how the release build points at a prebuilt frontend.

use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let dist = std::env::var_os("MUIS_UI_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../../src-ui/dist"));

    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-env-changed=MUIS_UI_DIST");
    println!("cargo:rerun-if-changed=build.rs");

    let mut files = Vec::new();
    if dist.join("index.html").is_file() {
        collect(&dist, &dist, &mut files);
        files.sort();
    }
    if files.is_empty() {
        println!(
            "cargo:warning=src-ui/dist is empty; muis-server will serve a placeholder page (run: npm run build --prefix src-ui)"
        );
    }

    let mut code = String::from("// Generated by build.rs; do not edit.\n");
    code.push_str(&format!(
        "pub const HAS_DIST: bool = {};\n\n",
        !files.is_empty()
    ));
    code.push_str("pub fn get(path: &str) -> Option<&'static [u8]> {\n    match path {\n");
    for name in &files {
        let abs = normalize(&dist.join(name));
        code.push_str(&format!("        {name:?} => Some(include_bytes!({abs:?})),\n"));
    }
    code.push_str("        _ => None,\n    }\n}\n");

    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap()).join("assets.rs");
    std::fs::write(out, code).expect("write embedded asset table");
}

/// Recursively collect files as `/`-separated paths relative to `root`.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(rel) = path.strip_prefix(root) {
            let name = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            out.push(name);
        }
    }
}

/// Absolute path with `/` separators, so the generated `include_bytes!`
/// works on Windows without escaping.
fn normalize(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}
